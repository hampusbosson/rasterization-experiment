import numpy as np

def generate_depth_curve_polygon(width, height, num_vertices=100, seed=42):

    """
    Generates a simple closed, non-self-intersecting polygon that resembles
    a contour/depth-curve region.
    The polygon is generated by sampling points around a center with varying radius.
    """

    rng = np.random.default_rng(seed)

    center_x = width * 0.5
    center_y = height * 0.5

    base_radius = min(width, height) * 0.30
    noise_strength = min(width, height) * 0.08

    angles = np.linspace(0, 2 * np.pi, num_vertices, endpoint=False)

    # Smooth radial variation, depth-curve-like
    radii = base_radius + noise_strength * (
        0.6 * np.sin(3 * angles)
        + 0.4 * np.sin(7 * angles + 0.8)
        + rng.normal(0, 0.15, size=num_vertices)
    )

    xs = center_x + radii * np.cos(angles)
    ys = center_y + radii * np.sin(angles)

    # Clamp to grid bounds
    xs = np.clip(xs, 1, width - 2)
    ys = np.clip(ys, 1, height - 2)

    return xs.astype(np.float64), ys.astype(np.float64)